import { expect, test } from "@playwright/test";
import { installWorkbenchFixture } from "./workbench-fixture";

test("workspace and settings share one collapse state without losing a settings draft", async ({ page }) => {
  await installWorkbenchFixture(page);
  const rail = page.getByRole("navigation", { name: "工作台导航" });
  await page.getByRole("button", { name: "收起侧栏", exact: true }).click();
  await rail.getByRole("button", { name: "设置", exact: true }).click();
  const sidebar = page.getByRole("navigation", { name: "设置分类" });
  await expect(sidebar).not.toBeVisible();
  const panel = (await page.locator(".settings-screen").boundingBox())!;
  const content = (await page.locator(".settings-content").boundingBox())!;
  expect(Math.abs(content.x - panel.x)).toBeLessThan(2);
  await page.getByRole("button", { name: "展开侧栏", exact: true }).click();
  await expect(sidebar).toBeVisible();
  await sidebar.getByRole("button", { name: "模型与连接", exact: true }).click();
  const draft = page.getByRole("textbox", { name: "模型密钥", exact: true });
  await draft.fill("isolated-ui-draft");
  await page.getByRole("button", { name: "收起侧栏", exact: true }).click();
  await expect(sidebar).not.toBeVisible();
  await expect(draft).toHaveValue("isolated-ui-draft");
  await rail.getByRole("button", { name: "工作区", exact: true }).click();
  await expect(page.getByRole("complementary", { name: "EchoCode 导航" })).not.toBeVisible();
  await page.keyboard.press("Control+b");
  await expect(page.getByRole("complementary", { name: "EchoCode 导航" })).toBeVisible();
  await rail.getByRole("button", { name: "设置", exact: true }).click();
  await expect(sidebar).toBeVisible();
  await expect(draft).toHaveValue("isolated-ui-draft");
  await page.keyboard.press("Control+b");
  await expect(sidebar).not.toBeVisible();
  await expect(page.getByRole("button", { name: "展开侧栏", exact: true })).toHaveAttribute("aria-expanded", "false");
});

test("compact settings navigation follows the toggle and the About logo matches the rail", async ({ page }, testInfo) => {
  await installWorkbenchFixture(page);
  await page.setViewportSize({ width: 720, height: 820 });
  await page.getByRole("button", { name: "切换浅色主题", exact: true }).click();
  const rail = page.getByRole("navigation", { name: "工作台导航" });
  await rail.getByRole("button", { name: "设置", exact: true }).click();
  const categories = page.getByRole("combobox", { name: "设置分类", exact: true });
  await expect(categories).not.toBeVisible();
  await page.getByRole("button", { name: "展开侧栏", exact: true }).click();
  await expect(categories).toBeVisible();
  await categories.selectOption("about");
  const brand = rail.getByRole("img", { name: "EchoCode", exact: true });
  const about = page.getByRole("img", { name: "EchoCode 标志", exact: true });
  await expect(about).toBeVisible();
  expect(await about.locator("svg").innerHTML()).toBe(await brand.locator("svg").innerHTML());
  const divider = page.locator(".rail-brand-divider");
  await expect(divider).toBeVisible();
  const markBox = (await brand.boundingBox())!, lineBox = (await divider.boundingBox())!;
  const navigationBox = (await rail.getByRole("button", { name: "工作区", exact: true }).boundingBox())!;
  expect(lineBox.y).toBeGreaterThan(markBox.y + markBox.height);
  expect(lineBox.y + lineBox.height).toBeLessThan(navigationBox.y);
  await page.getByRole("button", { name: "收起侧栏", exact: true }).click();
  await expect(categories).not.toBeVisible();
  await expect(page.getByRole("heading", { name: "关于 EchoCode", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("about-collapsed-light.png") });
});
